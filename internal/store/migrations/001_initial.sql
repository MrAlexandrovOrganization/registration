CREATE TABLE import_runs (source_hash TEXT PRIMARY KEY, imported_at TIMESTAMPTZ NOT NULL DEFAULT now(), users_count INTEGER NOT NULL);
CREATE TABLE milestone_notifications (epoch BIGINT NOT NULL, threshold INTEGER NOT NULL, PRIMARY KEY(epoch,threshold));
CREATE TABLE audit_events (id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, actor BIGINT NOT NULL, action TEXT NOT NULL, target BIGINT, created_at TIMESTAMPTZ NOT NULL DEFAULT now());
